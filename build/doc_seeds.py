#!/usr/bin/env python3
"""Turn question-round answers into documentation starts.

The registry's weakest rows are the ones nobody has written down. The question
round asks the people who run them; this script takes what they answered and
writes the beginning of a document per process — not finished documentation,
but the part that only they could supply, already captured and attributed.

    python3 build/doc_seeds.py              # write docs/drafts/<pid>.md
    python3 build/doc_seeds.py --dry-run    # show what would be written

Each draft is marked generated and is safe to re-run: a file is only rewritten
while it still carries the generated marker. The moment a human edits one and
removes the marker, this script leaves it alone forever — the seed grew.

Auth matches digest.py: the caller's own gcloud credentials.
"""
from __future__ import annotations

import argparse
import collections
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import digest  # token(), fetch(), known_processes() — same Firestore plumbing

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTDIR = ROOT / "docs" / "drafts"
MARKER = "<!-- generated by build/doc_seeds.py — edit freely; removing this line stops regeneration -->"

INVENTORY = ROOT / "data" / "inventory.md"


def row_info() -> dict[str, dict]:
    """pid -> {name, group, prose, state, a, d, i} from the inventory."""
    sys.path.insert(0, str(pathlib.Path(__file__).parent))
    import questions as qgen
    out = {}
    for r in qgen.load():
        raw = f"{r['group']} {r['name']}"
        slug = re.sub(r"[^a-z0-9]+", "-",
                      raw.lower().replace("&", " and ")).strip("-")[:120]
        out[slug] = r
    return out


def seed(pid: str, answers: list[dict], row: dict | None) -> str:
    answers = sorted(answers, key=lambda a: a.get("createdAt") or "")
    name = row["name"] if row else (answers[0].get("processName") or pid)
    L = [f"# {name}", "", MARKER, ""]
    if row:
        L += [f"_{row['group']} · state `{row['state']}` · "
              f"A{row['a']} D{row['d']} I{row['i']} at time of drafting_", ""]
    L += ["**Status: draft seeded from question-round answers.** What follows is "
          "what the people who run this said, lightly arranged — the part of the "
          "documentation only they could supply. Finishing it means turning their "
          "answers into procedure and deleting this paragraph.", ""]
    if row and row.get("prose"):
        L += ["## What this is", "", row["prose"], ""]
    L += ["## What we know"]
    for a in answers:
        who = a.get("name") or "Unknown"
        when = (a.get("createdAt") or "")[:10]
        L += ["", f"**Q: {a.get('question', '?')}**", "",
              f"> {a.get('text', '').strip()}", "",
              f"— {who}, {when}"]
    L += ["", "## Still to capture", "",
          "- Who does this today, and who is the backup?",
          "- Step by step, what happens — enough that a second person could run it?",
          "- What breaks most often, and what is the fix?",
          "- Where do the artifacts live (forms, sheets, admin pages)?", ""]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--account", default=None)
    a = ap.parse_args()

    bearer = digest.token(a.account)
    answers = digest.fetch("answers", bearer)
    if not answers:
        sys.exit("No answers in Firestore yet — nothing to seed.")

    by_pid = collections.defaultdict(list)
    for ans in answers:
        by_pid[ans.get("processId") or "__general__"].append(ans)
    by_pid.pop("__general__", None)   # unattached answers belong to the digest

    rows = row_info()
    written, skipped = 0, 0
    OUTDIR.mkdir(parents=True, exist_ok=True)
    for pid, ans in sorted(by_pid.items()):
        path = OUTDIR / f"{pid}.md"
        if path.exists() and MARKER not in path.read_text():
            skipped += 1
            continue   # a human took it over; never touch it again
        text = seed(pid, ans, rows.get(pid))
        if a.dry_run:
            print(f"--- would write {path.relative_to(ROOT)} "
                  f"({len(ans)} answer{'s' if len(ans) != 1 else ''})")
        else:
            path.write_text(text + "\n")
        written += 1

    verb = "would write" if a.dry_run else "wrote"
    print(f"{verb} {written} draft{'s' if written != 1 else ''} to docs/drafts/"
          + (f"; left {skipped} human-owned file{'s' if skipped != 1 else ''} alone"
             if skipped else ""))


if __name__ == "__main__":
    main()
